// Package secretbox encrypts small secrets (API tokens, webhook secrets) before they are stored,
// so a leaked database dump or backup does not leak the credentials of every shop.
//
// It uses AES-256-GCM: authenticated encryption, so a changed ciphertext fails to decrypt instead
// of decrypting to garbage. The key never touches the database; it comes from the environment.
//
// Sealed format: version (1 byte) | nonce (12 bytes) | ciphertext+tag. The version byte leaves
// room to rotate to a new key or algorithm later while old values still decrypt.
package secretbox

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"encoding/base64"
	"errors"
	"fmt"
)

// KeySize is the AES-256 key length in bytes.
const KeySize = 32

const version1 byte = 1

// ErrDecrypt means the value cannot be opened: wrong key, wrong context (associated data),
// or the bytes were changed. The reasons are deliberately not told apart.
var ErrDecrypt = errors.New("secretbox: cannot decrypt")

type Box struct {
	aead cipher.AEAD
}

// New returns a Box for a 32-byte key.
func New(key []byte) (*Box, error) {
	if len(key) != KeySize {
		return nil, fmt.Errorf("secretbox: key must be %d bytes, got %d", KeySize, len(key))
	}
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, fmt.Errorf("secretbox: %w", err)
	}
	aead, err := cipher.NewGCM(block)
	if err != nil {
		return nil, fmt.Errorf("secretbox: %w", err)
	}
	return &Box{aead: aead}, nil
}

// ParseKey decodes a base64 key, as generated by `openssl rand -base64 32`.
func ParseKey(encoded string) ([]byte, error) {
	key, err := base64.StdEncoding.DecodeString(encoded)
	if err != nil {
		return nil, errors.New("secretbox: key is not valid base64")
	}
	if len(key) != KeySize {
		return nil, fmt.Errorf("secretbox: key must be %d bytes (base64 of `openssl rand -base64 32`), got %d", KeySize, len(key))
	}
	return key, nil
}

// Seal encrypts plaintext. context is authenticated but not stored ("associated data"): the
// value only opens with the same context. Passing where the value belongs (e.g. the row and
// column) means a value copied into another row or column cannot be decrypted there.
func (b *Box) Seal(plaintext []byte, context string) []byte {
	// A fresh random nonce for every value: GCM must never reuse a nonce with the same key.
	nonce := make([]byte, b.aead.NonceSize())
	rand.Read(nonce) // never fails since Go 1.24

	out := make([]byte, 0, 1+len(nonce)+len(plaintext)+b.aead.Overhead())
	out = append(out, version1)
	out = append(out, nonce...)
	return b.aead.Seal(out, nonce, plaintext, []byte(context))
}

// Open decrypts a value made by Seal with the same context.
func (b *Box) Open(sealed []byte, context string) ([]byte, error) {
	n := b.aead.NonceSize()
	if len(sealed) < 1+n+b.aead.Overhead() || sealed[0] != version1 {
		return nil, ErrDecrypt
	}
	plaintext, err := b.aead.Open(nil, sealed[1:1+n], sealed[1+n:], []byte(context))
	if err != nil {
		return nil, ErrDecrypt
	}
	return plaintext, nil
}
